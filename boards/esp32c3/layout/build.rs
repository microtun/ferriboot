//! Generate the board's constants from board.json and the chip description it
//! names (ferriboot-esp/chips/esp32c3.json). Flash partition geometry is
//! deliberately absent: target code reads the flashed partition table and
//! host tools read partitions.csv.
use std::path::Path;

use ferriboot_build::{read_board, write_out};

/// The values this board decides. Everything else is a chip fact.
const BOARD_KEYS: &[&str] = &["FLASH_SIZE"];

fn main() {
    let board = read_board(Path::new("board.json"), BOARD_KEYS);
    assert_eq!(board.chip, "esp32c3", "this is an ESP32-C3 board");
    let mut rust = String::from(
        "// @generated by boards/esp32c3/layout/build.rs from board.json and its chip.\n",
    );
    rust.push_str(&board.rust_consts());
    write_out("layout.rs", rust);
}
