//! Generate the chip's constants from `chips/rp2350`, export the
//! application linker contract and publish the chip to dependent binaries.
//! Only chip facts are used here; boards pass their flash map as a value.
use std::fmt::Write as _;

use ferriboot_build::{
    named_values, out_dir, publish_chip, require_target, selected_chip, write_out,
};

/// Chip features, the chip description each selects and its target triple.
const FEATURES: &[(&str, &str, &str)] = &[
    ("rp235xa", "rp2350", "thumbv8m.main-none-eabihf"),
    ("rp235xb", "rp2350", "thumbv8m.main-none-eabihf"),
];

fn main() {
    let names: Vec<&str> = FEATURES.iter().map(|(feature, ..)| *feature).collect();
    let feature = selected_chip("ferriboot-rp", &names);
    let (_, chip, target) = *FEATURES.iter().find(|(f, ..)| *f == feature).unwrap();
    require_target("ferriboot-rp", chip, target);

    let values = named_values(ferriboot_chip_rp2350::VALUES);
    publish_chip(chip);

    let mut rust = String::from("// @generated by ferriboot-rp/build.rs from chips/rp2350.\n");
    for (name, value) in &values {
        writeln!(rust, "pub const {name}: u32 = {value:#010x};").unwrap();
    }
    write_out("chip.rs", rust);

    // Included by the memory.x of every application, after its regions.
    write_out("ferriboot-rp.x", include_str!("ld/ferriboot-rp.x"));
    println!("cargo:rustc-link-search={}", out_dir().display());
    println!("cargo:rerun-if-changed=ld/ferriboot-rp.x");
}
