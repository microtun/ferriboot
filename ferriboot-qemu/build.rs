//! Generate the machine's constants from `chips/<machine>.json` and publish
//! the machine to dependent binaries. Only machine facts are used here; the
//! board passes its flash map as a value.
use std::{fmt::Write as _, path::Path};

use ferriboot_build::{publish_chip, read_values_exact, require_target, selected_chip, write_out};

/// Supported machines, the Cargo feature selecting each and its target triple.
const MACHINES: &[(&str, &str)] = &[("mps2-an385", "thumbv7m-none-eabi")];

/// The machine description schema: every machine defines exactly these values.
const KEYS: &[&str] = &[
    "FLASH_SIZE",
    "ERASE_SIZE",
    "HEADER_SIZE",
    "SECURITY_COUNTER_CAPACITY",
    "APP_XIP_BASE",
    "RAM_BASE",
    "BOOT_INFO_ADDRESS",
    "BOOT_INFO_SIZE",
    "RESET_MARKER",
    "SPI_BASE",
    "SPI_CS",
    "EFUSE_BASE",
    "TRNG_BASE",
    "UART_BASE",
];

fn main() {
    let names: Vec<&str> = MACHINES.iter().map(|(name, _)| *name).collect();
    let machine = selected_chip("ferriboot-qemu", &names);
    let target = MACHINES
        .iter()
        .find(|(name, _)| *name == machine)
        .unwrap()
        .1;
    require_target("ferriboot-qemu", machine, target);

    let json = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("chips")
        .join(format!("{machine}.json"));
    let values = read_values_exact(&json, KEYS);
    publish_chip(machine, &json);

    let mut rust = format!("// @generated by ferriboot-qemu/build.rs from chips/{machine}.json.\n");
    for (name, value) in &values {
        let ty = if name == "BOOT_INFO_SIZE" {
            "usize"
        } else {
            "u32"
        };
        writeln!(rust, "pub const {name}: {ty} = {value:#x};").unwrap();
    }
    write_out("chip.rs", rust);
}
