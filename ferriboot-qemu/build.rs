//! Generate the machine's constants from `boards/qemu/layout/src/board.rs` and publish
//! the machine to dependent binaries. Only machine facts are used here; the
//! board passes its flash map as a value.
use std::fmt::Write as _;

use ferriboot_build::{chip_values, publish_chip, require_target, selected_chip, write_out};

/// Supported machines, the Cargo feature selecting each and its target triple.
const MACHINES: &[(&str, &str)] = &[("mps2-an385", "thumbv7m-none-eabi")];

fn main() {
    let names: Vec<&str> = MACHINES.iter().map(|(name, _)| *name).collect();
    let machine = selected_chip("ferriboot-qemu", &names);
    let target = MACHINES
        .iter()
        .find(|(name, _)| *name == machine)
        .unwrap()
        .1;
    require_target("ferriboot-qemu", machine, target);

    let values = chip_values(machine);
    publish_chip(machine);

    let mut rust =
        String::from("// @generated by ferriboot-qemu/build.rs from layout/src/board.rs.\n");
    for (name, value) in &values {
        let ty = if name == "BOOT_INFO_SIZE" {
            "usize"
        } else {
            "u32"
        };
        writeln!(rust, "pub const {name}: {ty} = {value:#x};").unwrap();
    }
    write_out("chip.rs", rust);
}
